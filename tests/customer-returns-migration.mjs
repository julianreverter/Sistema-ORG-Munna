import assert from 'node:assert/strict';
import fs from 'node:fs';
import { pathToFileURL } from 'node:url';
const { PGlite } = await import(process.env.PGLITE_MODULE ? pathToFileURL(process.env.PGLITE_MODULE).href : '@electric-sql/pglite');
const db = await PGlite.create();
await db.exec(`
create role anon; create role authenticated;
create schema auth;
create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('test.uid',true),'')::uuid$$;
create type stock_status as enum ('stock','despachado','baja');
create table profiles(id uuid primary key,display_name text,email text,active boolean,role text);
insert into profiles values ('00000000-0000-0000-0000-000000000001','Admin','admin@example.test',true,'administracion');
create function public.current_role() returns text language sql stable security definer as $$select role from public.profiles where id=auth.uid() and active$$;
create function public.is_admin() returns boolean language sql stable as $$select public.current_role()='administracion'$$;
create table clients(id bigint primary key);
insert into clients values(1),(2);
create table dispatches(id bigint primary key,client_id bigint references clients,remittance_number text,status text);
insert into dispatches values(1,1,'R-001','emitido'),(2,2,'R-002','emitido');
create table production_units(id bigint primary key,unique_code text unique,status stock_status,weight_kg numeric,units integer,dispatched_at timestamptz);
insert into production_units values(1,'001','despachado',null,20,now()),(2,'002','despachado',null,10,now()),(3,'003','despachado',7.5,null,now());
create table dispatch_items(id bigint primary key,dispatch_id bigint references dispatches,production_unit_id bigint unique references production_units,weight_kg numeric,units integer,unit_price numeric,discount_pct numeric,line_total numeric);
insert into dispatch_items values(1,1,1,null,20,1500,35,19500),(2,1,2,null,10,6000,35,39000),(3,2,3,7.5,null,1000,0,7500);
create table customer_account_adjustments(id bigint generated always as identity primary key,client_id bigint references clients,movement_date date,movement_type text,concept text,signed_amount numeric check(signed_amount<>0),notes text,created_by uuid references profiles);
grant usage on schema public,auth to authenticated;
grant select,insert,update on all tables in schema public to authenticated;
grant usage,select on all sequences in schema public to authenticated;
select set_config('test.uid','00000000-0000-0000-0000-000000000001',false);
`);
await db.exec(fs.readFileSync(new URL('../supabase/migrations/20261101233725_stock_removal_audit.sql',import.meta.url),'utf8'));
await db.exec(fs.readFileSync(new URL('../supabase/migrations/20261103192925_customer_returns.sql',import.meta.url),'utf8'));
await db.exec('set role authenticated');
const ret=(dispatch,code,reason='No entró en el freezer',comment='')=>db.query('select register_customer_return($1,$2,$3,$4) as receipt',[dispatch,code,reason,comment]);
await assert.rejects(()=>ret(1,'003'),/no pertenece/);
await assert.rejects(()=>ret(1,'001','Otro','  '),/comentario/);
await assert.rejects(()=>ret(1,'001','Motivo inventado'),/motivo/);
const first=(await ret(1,'001')).rows[0].receipt;
assert.equal(Number(first.amount),19500);
assert.equal(first.creditNoteNumber,'NC-D-000001');
assert.equal((await db.query('select status from production_units where id=1')).rows[0].status,'stock');
assert.equal(Number((await db.query('select signed_amount from customer_account_adjustments')).rows[0].signed_amount),-19500);
assert.equal(Number((await db.query('select units from production_units where id=1')).rows[0].units),20);
await assert.rejects(()=>ret(1,'001'),/ya fue devuelta/);
await assert.rejects(()=>db.exec("update customer_returns set amount=1 where id=1"),/permission denied/);
await assert.rejects(()=>db.exec('delete from customer_returns where id=1'),/permission denied/);
// The same barcode can leave again and creates a new, independently returnable delivery.
await db.exec("insert into dispatch_items values(4,2,1,null,20,1600,0,32000,null); update production_units set status='despachado',dispatched_at=now() where id=1");
await assert.rejects(()=>ret(1,'001'),/ya fue devuelta/);
await ret(2,'001','Pedido incorrecto');
assert.equal(Number((await db.query('select count(*) from customer_returns')).rows[0].count),2);
assert.equal(Number((await db.query('select sum(signed_amount) as credit from customer_account_adjustments')).rows[0].credit),-51500);
// Failure after financial writes must roll back the receipt, credit and stock transition together.
await db.exec('reset role');
await db.exec("create function fail_restock() returns trigger language plpgsql as $$begin if new.id=2 and new.status='stock' then raise exception 'test restock failure'; end if; return new; end$$; create trigger fail_restock before update on production_units for each row execute function fail_restock(); set role authenticated");
await assert.rejects(()=>ret(1,'002'),/test restock failure/);
assert.equal(Number((await db.query('select count(*) from customer_returns')).rows[0].count),2);
assert.equal((await db.query('select returned_at from dispatch_items where id=2')).rows[0].returned_at,null);
assert.equal((await db.query('select status from production_units where id=2')).rows[0].status,'despachado');
await db.exec("reset role; update profiles set role='maestro_heladero'; set role authenticated");
await assert.rejects(()=>ret(2,'003'),/Administración/);
assert.equal((await db.query('select * from customer_returns')).rows.length,0);
await db.exec("reset role; update profiles set role='administracion',active=false; set role authenticated");
await assert.rejects(()=>ret(2,'003'),/Administración/);
await db.exec('reset role');
assert.equal(Number((await db.query('select count(*) from production_units')).rows[0].count),3);
await db.close();
console.log('OK: complete returns, original discounted credit, RLS, duplicate prevention, re-dispatch, and transactional rollback.');

