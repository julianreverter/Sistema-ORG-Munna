import assert from 'node:assert/strict';
import fs from 'node:fs';
import { pathToFileURL } from 'node:url';
const { PGlite } = await import(process.env.PGLITE_MODULE ? pathToFileURL(process.env.PGLITE_MODULE).href : '@electric-sql/pglite');
const db=await PGlite.create();
await db.exec(`create role anon; create role authenticated;
create table production_units(id bigint generated always as identity primary key,unique_code text not null unique,weight_kg numeric);
insert into production_units(unique_code,weight_kg) values('004793',3.860),('004794',3.250),('CAJ00001',null);
grant select,insert on production_units to authenticated; grant usage on all sequences in schema public to authenticated;`);
const sql=fs.readFileSync(new URL('../supabase/migrations/20261103194944_server_production_codes.sql',import.meta.url),'utf8');
await db.exec('begin;'+sql+'commit;');
await db.exec(fs.readFileSync(new URL('../supabase/migrations/20261103195624_production_counter_catchup.sql',import.meta.url),'utf8'));
await db.exec("insert into production_units(unique_code,weight_kg) values('004800',4); set role authenticated;");
const inserts=await Promise.all(Array.from({length:100},()=>db.query('insert into production_units(weight_kg) values(4) returning unique_code')));
const codes=inserts.map(result=>result.rows[0].unique_code);
assert.equal(codes[0],'004795');
assert.equal(new Set(codes).size,100);
assert.equal(codes.includes('004800'),false);
await db.exec("insert into production_units(weight_kg,registration_id) values(3,'10000000-0000-4000-8000-000000000001')");
await assert.rejects(()=>db.exec("insert into production_units(weight_kg,registration_id) values(3,'10000000-0000-4000-8000-000000000001')"),/duplicate key/);
await assert.rejects(()=>db.exec("insert into production_units(unique_code,weight_kg) values('004794',3.86)"),/duplicate key/);
await db.exec("reset role; select setval('production_barcode_seq',999999,false); set role authenticated;");
assert.equal((await db.query('insert into production_units(weight_kg) values(4) returning unique_code')).rows[0].unique_code,'999999');
assert.equal((await db.query('insert into production_units(weight_kg) values(4) returning unique_code')).rows[0].unique_code,'1000000');
assert.equal(Number((await db.query("select weight_kg from production_units where unique_code='004793'")).rows[0].weight_kg),3.86);
await db.close();
console.log('OK: server allocation, historical max, uniqueness, request idempotency constraint, and seven-digit rollover.');
