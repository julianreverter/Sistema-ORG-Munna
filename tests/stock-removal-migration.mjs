// Run with PGLITE_MODULE pointing to an installed @electric-sql/pglite module.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { pathToFileURL } from 'node:url';
const { PGlite } = await import(process.env.PGLITE_MODULE ? pathToFileURL(process.env.PGLITE_MODULE).href : '@electric-sql/pglite');
const db = await PGlite.create();
await db.exec(`
create role anon; create role authenticated;
create schema auth;
create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('test.uid',true),'')::uuid $$;
create function public.current_role() returns text language sql stable as $$ select case when auth.uid() is not null then 'maestro_heladero' end $$;
create type public.stock_status as enum ('stock','despachado','baja');
create table profiles(id uuid primary key, display_name text, email text, active boolean);
insert into profiles values ('00000000-0000-0000-0000-000000000001','Operador','operador@example.test',true);
create table production_units(id bigint primary key, unique_code text, status stock_status default 'stock', weight_kg numeric, units integer);
create table dispatch_items(id bigint primary key, production_unit_id bigint references production_units);
insert into production_units values (1,'001','stock',7.1,null),(2,'002','despachado',7.2,null),(3,'003','stock',null,20),(4,'004','stock',7.4,null),(5,'005','stock',7.5,null);
`);
const migrations = fs.readdirSync(new URL('../supabase/migrations/', import.meta.url));
const sql = fs.readFileSync(new URL('../supabase/migrations/' + migrations.find(x => x.endsWith('_stock_removal_audit.sql')), import.meta.url),'utf8');
await db.exec(sql);
await db.exec(sql);
const remove = (id, reason, comment = '') => db.query("update production_units set status='baja',deletion_reason=$2,deletion_comment=$3 where id=$1 returning *", [id,reason,comment]);
await assert.rejects(() => remove(1,'Error en etiquetado'), /autorizado/);
await db.exec("select set_config('test.uid','00000000-0000-0000-0000-000000000001',false)");
await assert.rejects(() => remove(1,'Otro','  '), /comentario/);
await assert.rejects(() => remove(1,'invalido'), /motivo/);
await assert.rejects(() => remove(1,'Otro','x'.repeat(2001)), /comentario/);
await assert.rejects(() => remove(2,'Error en pesaje'), /stock/);
const removed = (await remove(1,'Error en etiquetado',' Confusión con frutilla al agua ')).rows[0];
assert.equal(removed.deletion_comment,'Confusión con frutilla al agua');
assert.equal(removed.deleted_by_name,'Operador');
assert.equal(removed.deleted_by,'00000000-0000-0000-0000-000000000001');
assert.ok(removed.deleted_at);
assert.equal(Number(removed.weight_kg),7.1);
await assert.rejects(() => remove(1,'Error en pesaje'), /modificarse/);
await assert.rejects(() => db.exec("update production_units set status='despachado' where id=1"), /despacharse/);
await assert.rejects(() => db.exec('insert into dispatch_items values (1,1)'), /disponible/);
await assert.rejects(() => db.exec('delete from production_units where id=1'), /conserva/);
await assert.rejects(() => db.exec("update production_units set deleted_by_name='Inventado' where id=4"), /solo se guardan/);
await db.exec('insert into dispatch_items values (2,4)');
await assert.rejects(() => remove(4,'Error en pesaje'), /despacho/);
await db.exec("update profiles set active=false");
await assert.rejects(() => remove(5,'Otro','Prueba'), /inactivo/);
await db.exec("update profiles set active=true");
assert.equal((await remove(3,'Mal formulado (a desperdicio)')).rows[0].units,20);
assert.equal((await remove(5,'Otro','Detalle obligatorio')).rows[0].deletion_comment,'Detalle obligatorio');
assert.equal(Number((await db.query('select count(*) from production_units')).rows[0].count),5);
await db.close();
console.log('OK: migration repeatable, audit preserved, invalid reasons/comments rejected, dispatched/removed units protected, unit counts preserved.');
